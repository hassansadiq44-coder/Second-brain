// Builds ./www from ./src: bundles the Cairo font + Supabase client locally (no CDN, works offline).
import fs from 'node:fs'; import path from 'node:path'; import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const src = path.join(root, 'src'), out = path.join(root, 'www');
fs.rmSync(out, { recursive: true, force: true }); fs.mkdirSync(out, { recursive: true });
fs.cpSync(src, out, { recursive: true });

// --- Cairo font (same typeface as the original app), latin + arabic subsets, weights 400-900
const fontDir = path.dirname(require.resolve('@fontsource/cairo/package.json')) + '/files';
fs.mkdirSync(path.join(out, 'fonts'), { recursive: true });
const ranges = {
  arabic: 'U+0600-06FF,U+0750-077F,U+0870-088E,U+0890-0891,U+0897-08E1,U+08E3-08FF,U+200C-200E,U+2010-2011,U+204F,U+2E41,U+FB50-FDFF,U+FE70-FE74,U+FE76-FEFC',
  latin: 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD',
  'latin-ext': 'U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+0304,U+0308,U+0329,U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C0,U+2113,U+2C60-2C7F,U+A720-A7FF'
};
let css = '/* generated by scripts/prepare-web.mjs: Cairo (OFL) bundled locally */\n';
for (const subset of Object.keys(ranges)) for (const w of [400, 500, 600, 700, 800, 900]) {
  const f = `cairo-${subset}-${w}-normal.woff2`;
  if (!fs.existsSync(path.join(fontDir, f))) { console.warn('missing font file', f); continue; }
  fs.copyFileSync(path.join(fontDir, f), path.join(out, 'fonts', f));
  css += `@font-face{font-family:'Cairo';font-style:normal;font-display:swap;font-weight:${w};src:url(${f}) format('woff2');unicode-range:${ranges[subset]};}\n`;
}
fs.writeFileSync(path.join(out, 'fonts', 'fonts.css'), css);

// --- Supabase client (UMD build exposes window.supabase)
const sbDir = path.dirname(require.resolve('@supabase/supabase-js/package.json'));
const umd = path.join(sbDir, 'dist', 'umd', 'supabase.js');
if (!fs.existsSync(umd)) throw new Error('supabase UMD build not found at ' + umd);
fs.mkdirSync(path.join(out, 'vendor'), { recursive: true });
fs.copyFileSync(umd, path.join(out, 'vendor', 'supabase.js'));
console.log('www ready:', fs.readdirSync(out).join(', '));
